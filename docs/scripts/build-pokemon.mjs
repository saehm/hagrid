/**
 * Builds the Pokémon showcase from `scripts/pokemon.json`.
 *
 * That file used to carry 18 columns, which were the six base stats *three
 * times* — every triple agreed to within 0.003 — and this script sliced the
 * first six off and checked the other two blocks still matched. The duplicates
 * have since been stripped from the file itself, so the columns are the six
 * stats and nothing else. Keeping all eighteen would have weighted every stat
 * three times over and told the projection the data had three times the
 * structure it really has.
 *
 *   node scripts/build-pokemon.mjs [--sweep]
 */
import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import * as druid from "@saehrimnir/druidjs";
import { label_agreement } from "./representations.mjs";
import { candidates, evaluate, report } from "./projection-quality.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const IN = resolve(here, "pokemon.json");
const OUT = resolve(here, "../src/data/pokemon-2d.json");
const SWEEP = process.argv.includes("--sweep");

const STATS = ["HP", "Attack", "Defense", "Sp. Atk", "Sp. Def", "Speed"];

const raw = JSON.parse(readFileSync(IN, "utf8"));

// One column per stat, in the order STATS names them. A file that disagrees is
// a different file, and silently projecting it would be worse than stopping.
const wrong = raw.values.findIndex((r) => r.length !== STATS.length);
if (wrong >= 0) {
    throw new Error(
        `${IN}: row ${wrong} has ${raw.values[wrong].length} columns, expected ${STATS.length}`,
    );
}

const stats = raw.values;
const labels = raw.labels.map((l) => l.trim());
const numbers = raw.names.map((n) => Number(n.split("_")[0]));
const names = raw.names.map((n) => n.split("_").slice(1).join("_"));

// Already min-max normalised per stat, and every stat is on the same 0..1
// footing, so standardising again would only re-weight them by their spread.
const high = stats;
const Z = druid.Matrix.from(high);

// The primary type is the label that matters — dual typings are 62 distinct
// strings, too fragmented to say anything about neighbourhoods.
const primary = labels.map((l) => l.split(/\s+/)[0]);
console.log(`${stats.length} pokemon, ${new Set(labels).size} typings, ${new Set(primary).size} primary types`);
console.log(`label agreement in stat space: ${(label_agreement(high, primary) * 100).toFixed(1)}%`);

function project(method, params) {
    const Y = new druid[method](Z, params).transform();
    const pts = stats.map((_, i) => [Y.entry(i, 0), Y.entry(i, 1)]);
    return pts.every(([x, y]) => Number.isFinite(x) && Number.isFinite(y)) ? pts : null;
}

// The winner of `--sweep`, pinned so a plain run reproduces the shipped file
// rather than a near-miss: it took mean rank 3.0 of 20 candidates over the six
// sickle metrics, against 5.0 for the perplexity-20 runs and 9.3 for the best
// UMAP. Re-run the sweep if the data changes.
let chosen = { method: "TSNE", params: { seed: 1, perplexity: 40, epsilon: 5 } };
let points = project(chosen.method, chosen.params);

if (SWEEP) {
    const scored = [];
    for (const c of candidates()) {
        const pts = project(c.method, c.params);
        if (!pts) continue;
        scored.push({
            ...c,
            points: pts,
            // Typing barely relates to stats, so rank on preservation alone.
            scores: evaluate(high, pts),
        });
    }
    const best = report(scored);
    chosen = { method: best.method, params: best.params };
    points = best.points;
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
    OUT,
    JSON.stringify({
        name: "Pokémon",
        source: "scripts/pokemon.json",
        method: chosen.method,
        params: chosen.params,
        note: "Generated by scripts/build-pokemon.mjs — do not edit by hand.",
        stats: STATS,
        numbers,
        names,
        labels,
        values: stats.map((r) => r.map((v) => Math.round(v * 10000) / 10000)),
        points,
    }),
);
console.log(
    `\n${stats.length} pokemon, ${chosen.method} ${JSON.stringify(chosen.params)} → ${OUT}`,
);
