/**
 * Vendors the image datasets from the original HaGrid demo into this site.
 *
 * The demo shipped two image collections — 1 353 flower photographs and 8 535
 * painting crops — of which its CSVs reference only 560 and 800. Copying the
 * directories wholesale would add 243 MB to the repository for images no page
 * ever asks for; taking the referenced ones and re-encoding them at the size
 * they are actually drawn brings both sets to about 2 MB together.
 *
 * The source lives outside this repository, so this is a one-off vendoring
 * step rather than part of the build: the output is committed. Point it at a
 * copy of the demo's `static/` directory to re-run it.
 *
 *   node scripts/build-images.mjs [path-to-demo-static]
 *
 * Output:
 *   public/showcase/<set>/<name>.webp   the thumbnails, served as files
 *   src/data/<set>-2d.json              points, labels and names
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE =
    process.argv[2] ??
    "//wsl.localhost/Arch/home/saehrimnir/projects/HaGrid/hagrid/hagrid_demo/static";

/*
 * 64px covers the largest the thumbnails are ever drawn: a lens cell is about
 * 30px, and a glyph in the Images showcase reaches roughly 50px at the coarsest
 * grid. Never enlarged — the flowers are 50x50 at source, and upscaling them
 * would spend bytes inventing detail that is not in the original.
 */
const MAX_PX = 64;
const SETS = ["flowers", "paintings"];

/** `UMAP_1,UMAP_2,labels,filename` — the demo's own column order. */
function parse(csv) {
    const [header, ...rows] = csv.trim().split(/\r?\n/);
    const cols = header.split(",");
    const at = (name) => cols.indexOf(name);
    const [x, y, label, file] = [at("UMAP_1"), at("UMAP_2"), at("labels"), at("filename")];
    return rows.map((line) => {
        const f = line.split(",");
        return { x: +f[x], y: +f[y], label: f[label], name: f[file] };
    });
}

for (const set of SETS) {
    const csv_path = join(SOURCE, "data", `${set}.csv`);
    if (!existsSync(csv_path)) {
        console.error(`${csv_path} not found — pass the demo's static/ directory as argv[2]`);
        process.exit(1);
    }
    const rows = parse(readFileSync(csv_path, "utf8"));

    const out_dir = resolve(here, "../public/showcase", set);
    rmSync(out_dir, { recursive: true, force: true });
    mkdirSync(out_dir, { recursive: true });

    let bytes = 0;
    let source_bytes = 0;
    for (const row of rows) {
        const src = join(SOURCE, "images", set, `${row.name}.png`);
        const buf = readFileSync(src);
        source_bytes += buf.length;
        const webp = await sharp(buf)
            .resize(MAX_PX, MAX_PX, { fit: "inside", withoutEnlargement: true })
            .webp({ quality: 82 })
            .toBuffer();
        writeFileSync(join(out_dir, `${row.name}.webp`), webp);
        bytes += webp.length;
    }

    const classes = [...new Set(rows.map((r) => r.label))].sort();
    writeFileSync(
        resolve(here, "../src/data", `${set}-2d.json`),
        JSON.stringify({
            name: set === "flowers" ? "Flowers" : "Paintings",
            source: "HaGrid demo (hagrid_demo/static)",
            note: "Generated by scripts/build-images.mjs — do not edit by hand.",
            method: "UMAP",
            params: { note: "projection precomputed in the original demo" },
            dir: `showcase/${set}`,
            extension: "webp",
            classes,
            names: rows.map((r) => r.name),
            labels: rows.map((r) => r.label),
            points: rows.map((r) => [r.x, r.y]),
        }),
    );

    console.log(
        `${set.padEnd(10)} ${rows.length} images, ${classes.length} classes, ` +
            `${(source_bytes / 1048576).toFixed(1)} MB → ${(bytes / 1048576).toFixed(2)} MB webp`,
    );
    console.log(`           classes: ${classes.join(", ")}`);
}
