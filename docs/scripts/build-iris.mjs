/**
 * Projects IRIS to 2D once, at build time, and writes the result next to the
 * showcase page.
 *
 * Doing it here rather than in the browser keeps the page instant and the
 * layout stable: UMAP is stochastic, and a showcase that rearranges itself on
 * every reload is not much of a reference. The seed is fixed so re-running
 * this reproduces the same projection.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { IRIS } from "@saehrimnir/mistle";
import * as druid from "@saehrimnir/druidjs";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../src/data/iris-2d.json");

const method = process.argv[2] ?? "UMAP";
const seed = Number(process.argv[3] ?? 1212);

if (!(method in druid)) {
    throw new Error(`unknown projection ${method}; have ${Object.keys(druid).join(", ")}`);
}

// Standardise first: the four columns are in centimetres but span very
// different ranges (petal width 0.1–2.5 against sepal length 4.3–7.9), so a
// raw euclidean metric is dominated by sepal length.
const cols = IRIS.columns.map((c) => IRIS.statistics[c]);
const Z = druid.Matrix.from(
    IRIS.values.map((row) => row.map((v, j) => (v - cols[j].mean) / cols[j].std)),
);

const proj = new druid[method](Z, { seed });
const Y = proj.transform();
const rows = Y.to2dArray ?? Y;
const points = Array.from({ length: IRIS.values.length }, (_, i) => [
    Y.entry(i, 0),
    Y.entry(i, 1),
]);

if (!points.every(([x, y]) => Number.isFinite(x) && Number.isFinite(y))) {
    throw new Error(`${method} produced non-finite coordinates`);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
    OUT,
    JSON.stringify(
        {
            method,
            seed,
            note: "Generated by scripts/build-iris.mjs — do not edit by hand.",
            columns: IRIS.columns,
            labels: IRIS.labels,
            values: IRIS.values,
            points,
        },
        null,
        1,
    ),
);
console.log(`${method} (seed ${seed}) → ${points.length} points → ${OUT}`);
void rows;
