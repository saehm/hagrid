/**
 * Projects a dataset to 2D once, ahead of time, for the showcase pages.
 *
 * Doing it here rather than in the browser keeps the pages instant and the
 * layouts stable: the projections are stochastic, and a showcase that
 * rearranges itself on every reload is not much of a reference. Seeds are
 * fixed, so re-running reproduces the same result.
 *
 *   node scripts/build-dataset.mjs WINE            # a bundled mistle dataset
 *   node scripts/build-dataset.mjs openml:1499     # anything on OpenML
 *   node scripts/build-dataset.mjs WINE PaCMAP 42  # pick projection and seed
 *
 * Writes `src/data/<slug>-2d.json`, carrying the measurements, the class
 * labels, the per-column ranges the glyphs normalise against, and the points.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import * as mistle from "@saehrimnir/mistle";
import * as druid from "@saehrimnir/druidjs";

const here = dirname(fileURLToPath(import.meta.url));

/**
 * OpenML column names are often "V1", "V2", … — useful names, where we know
 * them, and a title for the page.
 */
const OPENML = {
    1499: {
        slug: "seeds",
        title: "Wheat kernels",
        columns: [
            "area", "perimeter", "compactness",
            "kernel length", "kernel width", "asymmetry", "groove length",
        ],
        classes: { 1: "Kama", 2: "Rosa", 3: "Canadian" },
    },
};

/** Bundled datasets whose class labels are bare codes. */
const BUNDLED = {
    WINE: {
        title: "Wine",
        classes: { 1: "Cultivar 1", 2: "Cultivar 2", 3: "Cultivar 3" },
    },
};

/** OpenML serves these as CSV with a header row and the class last. */
function parse_csv(raw, meta) {
    const lines = raw.trim().split(/\r?\n/);
    const header = lines[0].split(",").map((h) => h.replace(/^"|"$/g, "").trim());
    const rows = lines.slice(1).map((l) => l.split(",").map((c) => c.replace(/^"|"$/g, "").trim()));

    const last = header.length - 1;
    const columns = meta?.columns ?? header.slice(0, last);
    const values = rows.map((r) => r.slice(0, last).map(Number));
    const labels = rows.map((r) => meta?.classes?.[r[last]] ?? r[last]);

    if (values.some((v) => v.some((x) => !Number.isFinite(x)))) {
        throw new Error("non-numeric measurement; this loader only handles numeric CSV");
    }
    return { columns, values, labels };
}

async function load(source) {
    if (source.startsWith("openml:")) {
        const id = Number(source.slice(7));
        const meta = OPENML[id];
        const { raw_data } = await mistle.fetch_openml(id);
        const ds = parse_csv(raw_data, meta);
        return { ...ds, slug: meta?.slug ?? `openml-${id}`, title: meta?.title ?? `OpenML ${id}` };
    }
    const ds = mistle[source];
    if (!ds?.values) throw new Error(`unknown dataset ${source}`);
    const rename = BUNDLED[source]?.classes;
    return {
        columns: ds.columns,
        values: ds.values,
        labels: rename ? ds.labels.map((l) => rename[l] ?? l) : ds.labels,
        slug: source.toLowerCase(),
        title: BUNDLED[source]?.title ?? source,
    };
}

const source = process.argv[2] ?? "WINE";
const method = process.argv[3] ?? "UMAP";
const seed = Number(process.argv[4] ?? 1212);

const { columns, values, labels, slug, title } = await load(source);
if (!(method in druid)) throw new Error(`unknown projection ${method}`);

// Standardise before projecting: columns measured on different scales would
// otherwise let the largest one dominate the metric.
const n = values.length;
const d = columns.length;
const mean = Array.from({ length: d }, (_, j) => values.reduce((s, r) => s + r[j], 0) / n);
const std = Array.from({ length: d }, (_, j) =>
    Math.sqrt(values.reduce((s, r) => s + (r[j] - mean[j]) ** 2, 0) / n) || 1,
);
const Z = druid.Matrix.from(values.map((row) => row.map((v, j) => (v - mean[j]) / std[j])));

const Y = new druid[method](Z, { seed }).transform();
const points = Array.from({ length: n }, (_, i) => [Y.entry(i, 0), Y.entry(i, 1)]);
if (!points.every(([x, y]) => Number.isFinite(x) && Number.isFinite(y))) {
    throw new Error(`${method} produced non-finite coordinates`);
}

// The glyphs normalise each column against its own range across the dataset,
// so two glyphs are comparable rather than each being scaled to itself.
const ranges = Array.from({ length: d }, (_, j) => [
    Math.min(...values.map((r) => r[j])),
    Math.max(...values.map((r) => r[j])),
]);

const OUT = resolve(here, `../src/data/${slug}-2d.json`);
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
    OUT,
    JSON.stringify(
        {
            name: title,
            source,
            method,
            seed,
            note: "Generated by scripts/build-dataset.mjs — do not edit by hand.",
            columns,
            ranges,
            labels,
            values,
            points,
        },
        null,
        1,
    ),
);
console.log(
    `${title}: ${n}x${d}, ${new Set(labels).size} classes, ${method} (seed ${seed}) → ${OUT}`,
);
