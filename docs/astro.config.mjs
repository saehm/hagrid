// @ts-check
import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";
import svelte from "@astrojs/svelte";
import starlightTypeDoc, { typeDocSidebarGroup } from "starlight-typedoc";
import starlightLlmsTxt from "starlight-llms-txt";
import remarkMath from "remark-math";
import rehypeKatex from "rehype-katex";
import { rehypeBaseLinks } from "./plugins/rehype-base-links.mjs";

// Settled (DOCU.md, open question 1): GitHub Pages as a project site, so the
// docs live under /hagrid/ rather than at a domain root. `base` covers every
// URL Astro and Starlight generate; the hand-written and TypeDoc-generated
// Markdown links are covered by `rehypeBaseLinks` below. starlight-llms-txt
// bakes absolute URLs into llms.txt from `site`.
const site = "https://saehm.github.io/hagrid";
const base = "/hagrid";

export default defineConfig({
    site,
    base,
    /*
     * Math is written as TeX in the Markdown itself — `$…$` inline, `$$…$$`
     * displayed — and rendered to HTML at build time by KaTeX. Nothing ships to
     * the browser but markup and the stylesheet.
     *
     * The MDX integration extends this config, so the same syntax works on the
     * .mdx pages. `<Math />` wraps the same renderer for the cases Markdown
     * cannot express: a caption, or a formula inside a component's props.
     */
    markdown: {
        remarkPlugins: [remarkMath],
        // Throwing is the point: a mistyped macro is a build failure rather
        // than a line of red \color{#cc0000} TeX shipped to the page.
        rehypePlugins: [
            [rehypeKatex, { throwOnError: true, strict: "warn" }],
            rehypeBaseLinks({ base }),
        ],
    },
    integrations: [
        starlight({
            title: "Hagrid",
            description: "Removes overlaps in scatterplots using space filling curves.",
            logo: {
                light: "./src/assets/light-hagrid.svg",
                dark: "./src/assets/dark-hagrid.svg",
                alt: "The logo",
            },
            favicon: "./src/assets/dark-hagrid.svg",
            social: [
                {
                    icon: "github",
                    label: "GitHub",
                    href: "https://github.com/saehm/hagrid",
                },
            ],
            plugins: [
                starlightTypeDoc({
                    entryPoints: ["../src/main.ts"],
                    tsconfig: "../tsconfig.json",
                    output: "api",
                    sidebar: { label: "API reference", collapsed: true },
                    typeDoc: {
                        // The library is one flat module; a page per export is
                        // easier to link into than one wall of text.
                        outputFileStrategy: "members",
                        useCodeBlocks: true,
                        expandObjects: true,
                        parametersFormat: "table",
                    },
                }),
                starlightLlmsTxt({
                    projectName: "Hagrid",
                    description:
                        "A JavaScript library that removes overlaps in scatterplots by snapping points onto a grid, using space filling curves and related techniques.",
                    // The generated API pages are already terse and repetitive;
                    // including them doubles llms-full.txt for little gain.
                    exclude: ["api/**"],
                    // Required, not a preference: the plugin renders each page
                    // through an Astro container that has no Svelte renderer, so
                    // any page importing a demo throws. Raw mode skips the render
                    // and emits the MDX source, import lines and all.
                    rawContent: true,
                }),
            ],
            sidebar: [
                {
                    label: "Start here",
                    items: [
                        { label: "Introduction", link: "/" },
                        { label: "Getting started", slug: "getting-started" },
                        { label: "Playground", slug: "playground" },
                    ],
                },
                {
                    label: "Techniques",
                    items: [{ autogenerate: { directory: "techniques" } }],
                },
                {
                    label: "Showcase",
                    // Named explicitly rather than autogenerated from the whole
                    // directory: `autogenerate` labels a subgroup with the
                    // folder name verbatim, which gives a lowercase "glyphs".
                    // A second kind of showcase gets its own entry here.
                    items: [
                        {
                            label: "Glyph",
                            items: [{ autogenerate: { directory: "showcase/glyphs" } }],
                        },
                        {
                            label: "Images",
                            items: [{ autogenerate: { directory: "showcase/images" } }],
                        },
                        {
                            label: "Lens",
                            items: [{ autogenerate: { directory: "showcase/lens" } }],
                        },
                    ],
                },
                typeDocSidebarGroup,
            ],
            // KaTeX's own stylesheet first, so the overrides in custom.css
            // (theme colours, scrolling display blocks) win over it.
            customCss: ["katex/dist/katex.min.css", "./src/styles/custom.css"],
        }),
        svelte(),
    ],
});
